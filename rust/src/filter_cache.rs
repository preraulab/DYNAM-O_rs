#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cache_candidates_prefer_override_then_runtime_install() {
        let dirs = candidate_filter_dirs_from(
            Some(PathBuf::from("/override")),
            Some(Path::new("/install/dynamo_rs.so")),
            Some(Path::new("/checkout/rust")),
        );
        assert_eq!(
            dirs,
            vec![
                PathBuf::from("/override"),
                PathBuf::from("/install/data_matlab_filters"),
                PathBuf::from("/checkout/rust/data_matlab_filters"),
                PathBuf::from("/checkout/data_matlab_filters"),
            ]
        );
    }

    #[test]
    fn filename_format_matches_cache() {
        // Spot-check every committed combination's naming convention.
        assert_eq!(
            sophase_cache_filename(100.0, (0.3, 1.5)),
            "sophase_sos_Fs100_0.3_1.5.npy"
        );
        assert_eq!(
            sophase_cache_filename(128.0, (0.5, 1.0)),
            "sophase_sos_Fs128_0.5_1.npy"
        );
        assert_eq!(
            sophase_cache_filename(512.0, (0.3, 5.0)),
            "sophase_sos_Fs512_0.3_5.npy"
        );
    }

    #[test]
    fn load_fs100_band_03_15() {
        // The committed file should be (9, 6).
        let sos = get_sophase_sos(100.0, (0.3, 1.5)).expect("expected cache hit");
        assert_eq!(sos.shape(), &[9, 6]);
    }

    #[test]
    fn cheby1_bandpass_designs_nonempty() {
        let sos = design_cheby1_bandpass_sos(4, 0.2, (0.3, 1.5), 100.0).unwrap();
        assert!(sos.nrows() > 0);
        assert_eq!(sos.ncols(), 6);
    }

    #[test]
    fn embedded_filters_match_on_disk() {
        // The build-time embed must be populated, parse via ReadNpyExt, and be
        // byte-equal to the on-disk file (so the embedded fallback is a perfect
        // substitute — no fidelity change vs the dir-search path).
        assert!(!EMBEDDED_FILTERS.is_empty(), "embedded filter set is empty");
        let fname = "sophase_sos_Fs100_0.3_1.5.npy";
        let (_, bytes) = EMBEDDED_FILTERS
            .iter()
            .find(|(n, _)| *n == fname)
            .expect("Fs100 0.3-1.5 should be embedded");
        let embedded = Array2::<f64>::read_npy(std::io::Cursor::new(*bytes))
            .expect("embedded npy should parse");
        assert_eq!(embedded.shape(), &[9, 6]);
        let on_disk = get_sophase_sos(100.0, (0.3, 1.5)).expect("on-disk cache hit");
        assert_eq!(embedded, on_disk, "embedded filter diverges from on-disk");
    }

    #[test]
    fn every_embedded_fs_covers_all_default_bands() {
        // Each sampling rate present in the embedded set must carry all six
        // canonical bands, so no (fs, band) pair a real cohort presents at a
        // known rate ever degrades to the cheby1 fallback. Fs=64 is the
        // regression case: 64 Hz recordings hit the fallback until 2026-09.
        let bands = [(0.3, 1.0), (0.3, 1.5), (0.3, 5.0), (0.5, 1.0), (0.5, 1.5), (0.5, 5.0)];
        let mut fss: Vec<u32> = EMBEDDED_FILTERS
            .iter()
            .filter_map(|(n, _)| {
                n.strip_prefix("sophase_sos_Fs")
                    .and_then(|r| r.split('_').next())
                    .and_then(|s| s.parse().ok())
            })
            .collect();
        fss.sort_unstable();
        fss.dedup();
        assert!(fss.contains(&64), "Fs=64 missing from embedded set: {fss:?}");
        for fs in fss {
            for band in bands {
                let fname = sophase_cache_filename(fs as f64, band);
                assert!(
                    EMBEDDED_FILTERS.iter().any(|(n, _)| *n == fname),
                    "embedded set missing {fname}"
                );
            }
        }
    }
}
